#!/usr/bin/env bash
# SessionStart hook. Prints what changed upstream since this branch diverged,
# which other branches are active, and this branch's handoff log. The output
# is added to Claude's context at the start of every session.
set -u
cd "${CLAUDE_PROJECT_DIR:-.}" 2>/dev/null || exit 0
git rev-parse --is-inside-work-tree >/dev/null 2>&1 || exit 0

git fetch --quiet --prune 2>/dev/null || true
branch=$(git rev-parse --abbrev-ref HEAD 2>/dev/null || echo "detached")
base="origin/main"

echo "## Repo context (generated by .claude/hooks/session-start.sh)"
echo "Branch: $branch"

if git rev-parse --verify -q "$base" >/dev/null; then
  behind=$(git rev-list --count "HEAD..$base" 2>/dev/null || echo 0)
  ahead=$(git rev-list --count "$base..HEAD" 2>/dev/null || echo 0)
  echo "Ahead of $base by $ahead commit(s), behind by $behind."
  if [ "$behind" -gt 0 ]; then
    echo
    echo "### New on $base since this branch diverged (merge or rebase before building on it)"
    git log --oneline --no-merges "HEAD..$base" | head -20
    echo
    echo "### Upstream changes to shared state and Claude config"
    git diff --stat "HEAD...$base" -- docs/STATE.md docs/decisions docs/handoffs CLAUDE.md .claude 2>/dev/null | head -30
  fi
fi

echo
echo "### Other branches touched recently"
git for-each-ref --sort=-committerdate \
  --format='%(committerdate:short)  %(refname:short)  %(subject)' refs/remotes/origin \
  | grep -v 'origin/HEAD' | grep -v "origin/$branch\$" | head -10

echo
echo "### Handoff log for this branch"
f="docs/handoffs/${branch//\//-}.md"
if [ -f "$f" ]; then tail -n 30 "$f"; else echo "(none yet — /handoff creates $f)"; fi

echo
echo "### Uncommitted changes"
git status --short | head -20
exit 0
