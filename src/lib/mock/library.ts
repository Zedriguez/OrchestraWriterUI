export function getProject(id: string): ProjectSummary | undefined {
  return PROJECTS.find((p) => p.id === id);
}

export function getProgram(id: string): Program | undefined {
  return PROGRAMS.find((p) => p.id === id);
}

export function projectsInProgram(programId: string): ProjectSummary[] {
  const program = getProgram(programId);
  if (!program) return [];
  return program.projectIds.map((id) => getProject(id)).filter((p): p is ProjectSummary => Boolean(p));
}
